0x90000000902e7e80 0x90000000902e7780 0x9000000090250d00 0x9000000090250fe0"

# Extra addresses from argv override the historical snapshot (pass them after the ELF path).
if [ $# -gt 0 ]; then
  ADDRS="$*"
fi

for a in $ADDRS; do
  echo "== $a"
  "$A2L" -f -C -i -e "$ELF" "$a"
done
